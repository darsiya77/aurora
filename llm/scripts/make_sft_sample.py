def main():
    rng = random.Random(7)
    rows = []
    for questions, answer in QA:
        for q in questions:
            rows.append({"messages": [{"role": "system", "content": SYSTEM},
                                      {"role": "user", "content": q},
                                      {"role": "assistant", "content": answer}]})
    # A few two-turn dialogs, so the model sees that history matters.
    for _ in range(12):
        (q1, a1), (q2, a2) = rng.sample([(rng.choice(qs), a) for qs, a in QA], 2)
        rows.append({"messages": [{"role": "system", "content": SYSTEM}, {"role": "user", "content": q1},
                                  {"role": "assistant", "content": a1}, {"role": "user", "content": q2},
                                  {"role": "assistant", "content": a2}]})
    rng.shuffle(rows)
    out = Path("data/sft/train.jsonl")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n", encoding="utf-8")
    print(f"saved {len(rows)} dialogs to {out}")


if __name__ == "__main__":
    main()
